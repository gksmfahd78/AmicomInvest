export function courseSlides(week: CourseWeek): CourseSlide[] {
  return [
    ...courseLessons[week.week].lessons.map((lesson) => ({
      title: lesson.title,
      points: lesson.slidePoints,
      example: lesson.slideExample,
      notes: lesson.paragraphs.join("\n\n"),
    })),
    ...week.slides.slice(3),
    ...courseDepth[week.week].slides,
    {
      title: "함께 실습하고 토론합니다",
      points: week.practice,
      example: week.discussion,
      notes: `실습 20분, 토론 10분을 배정합니다. 과제: ${week.homework}`,
    },
  ];
}
export function courseWeekFromHash(hash: string) {
  const match = hash.match(/^#education(?:\/week\/([1-8]))?$/);
  return match ? Number(match[1] || 1) : 1;
}
